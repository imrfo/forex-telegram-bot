def generate_persian_post(title, summary, category):
  client = genai.Client(api_key=GEMINI_API_KEY)
  prompt = f"""
تو یک تحلیل‌گر ارشد تکنیکال و فاندامنتال بازار فارکس هستی.
این خبر انگلیسی را به یک گزارش تحلیلی جذاب، حرفه‌ای و روان به زبان فارسی برای تلگرام تبدیل کن.

دستورالعمل‌ها:
۱. از ایموجی‌های متناسب و جذاب با تم بازار (🟢/📈 برای صعودی، 🔴/📉 برای نزولی، 📊 برای تکنیکال، ⚠️ برای هشدار) در متن استفاده کن.
۲. اگر در متن اعداد، سطوح قیمتی، مقاومت یا حمایت ذکر شده، حتماً در بخش تحلیل تکنیکال بیاور.
۳. تنها از تگ <b> برای بولد کردن کلمات استفاده کن و از تگ‌های دیگر HTML استفاده نکن.

تیتر خبر: {title}
خلاصه رویداد: {summary}
دسته‌بندی: {category}

قالب خروجی دقیقاً به این شکل باشد:
[ایموجی مناسب صعودی یا نزولی] <b>[تیتر جذاب، ژورنالیستی و فوری به فارسی]</b>

📌 <b>رویداد و خلاصه خبر:</b>
[۲ تا ۳ جمله شفاف از اصل خبر]

📊 <b>دیدگاه تحلیلی و تکنیکال:</b>
[نکات تکنیکال، وضعیت شکست سطوح یا رفتار قیمت طبق متن خبر]

💡 <b>اثر روی نمادها:</b>
[یک خط درباره جفت‌ارزها یا دارایی‌های تحت تاثیر مثل طلا، دلار، نفت و...]

⚠️ <i>سلب مسئولیت: این تحلیل صرفاً جنبه آگاهی‌بخشی دارد و پیشنهاد یا سیگنال خرید و فروش محسوب نمی‌شود. با مدیریت سرمایه و احتیاط معامله کنید.</i>

#{category.replace(' + ', ' #').replace('/', '_')} #فارکس_تحلیل #مدیریت_ریسک
"""
  response = client.models.generate_content(
      model="gemini-3.1-flash-lite", contents=prompt
  )

  post_text = response.text.strip()
  post_text += "\n\n🆔 @ForexPersianNews"
  return post_text
